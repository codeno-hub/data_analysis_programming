# Initialize temperature dataset and threshold
temperatures = [31, 35, 30, 38, 32]
threshold = 33

# 1. Summation and Average Calculation
total_sum = sum(temperatures)
average_temp = total_sum / len(temperatures)

# 2. Conditional loop for threshold analysis
exceed_count = 0
for temp in temperatures:
    if temp > threshold:
        exceed_count += 1

# Print Results
print(f"Calculated Average Temperature: {average_temp:.1f}°C")
print(f"Number of temperatures exceeding {threshold}°C: {exceed_count}")